    public void setInformation(String text) {
        txtInfo.setText(text);
        txtInfo.setCaretPosition(0);
    }

    /**
     * Convenience method for populating the dashboard from a database row
     * and a transaction query.
     */
    public void setDashboardInformation(
            String accountNumber,
            String customerName,
            String balance,
            String recentActivity
    ) {
        setBalance(balance);
        lblAccountNumber.setText("Account number: " + accountNumber);
        setInformation(
                "CUSTOMER: " + customerName + "\n"
                + "ACCOUNT NUMBER: " + accountNumber + "\n\n"
                + "RECENT ACTIVITY\n"
                + recentActivity
        );
    }

