    private void showChangePinDialog() {
        JPanel panel = new JPanel(new GridLayout(0, 2, 8, 8));
        panel.setBorder(new EmptyBorder(8, 8, 8, 8));

        JPasswordField currentPin = new JPasswordField();
        JPasswordField newPin = new JPasswordField();
        JPasswordField confirmPin = new JPasswordField();

        panel.add(new javax.swing.JLabel("Current PIN:"));
        panel.add(currentPin);
        panel.add(new javax.swing.JLabel("New PIN:"));
        panel.add(newPin);
        panel.add(new javax.swing.JLabel("Confirm new PIN:"));
        panel.add(confirmPin);

        int answer = JOptionPane.showConfirmDialog(
                this,
                panel,
                "Change PIN",
                JOptionPane.OK_CANCEL_OPTION,
                JOptionPane.PLAIN_MESSAGE
        );

        if (answer != JOptionPane.OK_OPTION) {
            return;
        }

        String current = new String(currentPin.getPassword()).trim();
        String updated = new String(newPin.getPassword()).trim();
        String confirmation = new String(confirmPin.getPassword()).trim();

        if (!current.matches("\\d{4,5}")) {
            showInputError("Enter your current 4 or 5 digit PIN.");
            return;
        }
        if (!updated.matches("\\d{4,5}")) {
            showInputError("The new PIN must contain 4 or 5 digits.");
            return;
        }
        if (!updated.equals(confirmation)) {
            showInputError("The new PIN and confirmation PIN do not match.");
            return;
        }

        /*
         * Connect this point to your ServiceLayer, for example:
         * ServiceLayer.changePin(accountNumber, current, updated);
         * Do not store or print PIN values in the dashboard.
         */
        setInformation("PIN CHANGE REQUEST\n\n"
                + "Your new PIN passed the form validation.\n"
                + "The database update should be called from your ServiceLayer here.");
        JOptionPane.showMessageDialog(
                this,
                "PIN details accepted. Connect the ServiceLayer update here.",
                "Change PIN",
                JOptionPane.INFORMATION_MESSAGE
        );
    }

    private void showForgottenPinDialog() {
        JPanel panel = new JPanel(new GridLayout(0, 2, 8, 8));
        panel.setBorder(new EmptyBorder(8, 8, 8, 8));

        JTextField accountNumber = new JTextField();
        JTextField idNumber = new JTextField();

        panel.add(new javax.swing.JLabel("Account number:"));
        panel.add(accountNumber);
        panel.add(new javax.swing.JLabel("ID number:"));
        panel.add(idNumber);

        int answer = JOptionPane.showConfirmDialog(
                this,
                panel,
                "Forgotten PIN / PIN Help",
                JOptionPane.OK_CANCEL_OPTION,
                JOptionPane.PLAIN_MESSAGE
        );

        if (answer != JOptionPane.OK_OPTION) {
            return;
        }

        if (accountNumber.getText().trim().isEmpty()
                || idNumber.getText().trim().isEmpty()) {
            showInputError("Enter both your account number and ID number.");
            return;
        }

        /*
         * Connect this point to your ServiceLayer verification method.
         * Never display the old PIN. A secure implementation should verify
         * the customer and then allow a new PIN to be created.
         */
        setInformation("PIN HELP REQUEST\n\n"
                + "Your identity details were captured for verification.\n"
                + "The ServiceLayer should verify them against MySQL before "
                + "allowing a new PIN to be created.");
        JOptionPane.showMessageDialog(
                this,
                "Your details are ready for database verification.",
                "PIN Help",
                JOptionPane.INFORMATION_MESSAGE
        );
    }

